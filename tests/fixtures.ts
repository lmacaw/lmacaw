export async function user(): Promise<User> {
	const id = crypto.randomUUID();
	const email = `${id}@example.com`;
	await env.DB.prepare('INSERT INTO users (id, email, created_at) VALUES (?, ?, ?)')
		.bind(id, email, Date.now()).run();
	return { id, email, isAdmin: false };
}

export function imageInput(overrides: Partial<NewItem> = {}): NewItem {
	return {
		original: new File([png], 'pixel.png', { type: 'image/png' }),
		thumbnail: new File([webp], 'thumbnail.webp', { type: 'image/webp' }),
		width: 1, height: 1, sha256: newKey(),
		...overrides
	};
}

export function createTestItem(owner: User, overrides: Partial<NewItem> = {}) {
	return createItem(unsignedEnv, owner.id, imageInput(overrides));
}

type Route = NonNullable<RequestEvent['route']['id']>;
export function eventFor<Path extends Route>(
	route: Path, path: string, actor: User | null, init?: RequestInit, id?: string, bindings?: Partial<Env>
) {
	const url = new URL(path, 'http://localhost:4173');
	const request = new Request(url, init);
	return {
		request, url, params: id === undefined ? {} : { id }, locals: { user: actor }, route: { id: route },
		platform: { env: { ...unsignedEnv, ...bindings } }
	} as unknown as RequestEvent<Path extends `${string}[id]${string}` ? { id: string } : Record<string, never>, Path>;
}

export const itemsRoute = '/api/v1/items';
export function listEvent(actor: User | null, search = '', bindings?: Partial<Env>) {
	return eventFor(itemsRoute, itemsRoute + search, actor, undefined, undefined, bindings);
}

export function uploadForm(input = imageInput()): FormData {
	const form = new FormData();
	form.set('file', new Blob([input.original], { type: input.original.type }), input.original.name);
	form.set('thumbnail', new Blob([input.thumbnail], { type: input.thumbnail.type }), input.thumbnail.name);
	form.set('sha256', input.sha256);
	form.set('width', String(input.width));
	form.set('height', String(input.height));
	return form;
}

export async function uploadEvent(actor: User | null, form = uploadForm(), bindings?: Partial<Env>) {
	// Serialize with the runtime's own multipart encoder and supply the wire length explicitly.
	const encoded = new Response(form);
	const contentType = encoded.headers.get('content-type')!;
	const body = await encoded.arrayBuffer();
	return eventFor(itemsRoute, itemsRoute, actor, {
		method: 'POST',
		headers: {
			'content-type': contentType,
			'content-length': String(body.byteLength)
		},
		body
	}, undefined, bindings);
}

/** R2 keys in the test bucket. Earlier tests in a file leave objects behind, so compare against a snapshot. */
export async function mediaKeys(): Promise<string[]> {
	return (await env.MEDIA.list()).objects.map((object) => object.key).sort();
}
